export type SortDirection = 'ascending' | 'descending';
export interface TableSort {
  key: string;
  direction: SortDirection;
}

export interface TableColumn<T> {
  /** Unique key. Also the default field to show and sort by: row[key]. */
  key: string;
  title: string;
  /** Column width: 120 (px) or "40%". Leave one column without a width so it takes the rest. */
  width?: number | string;
  /** Right-aligned numbers (the header title stays left-aligned, like the kit). */
  numeric?: boolean;
  /** Click the header to sort (default true). */
  sortable?: boolean;
  /** Value used for sorting (default row[key]). Return a number for numeric sorting. */
  sortValue?: (row: T) => string | number | Date | null | undefined;
  /** Cell content (default: row[key] as text). */
  render?: (row: T) => ReactNode;
}

export interface TableProps<T> {
  columns: TableColumn<T>[];
  rows: T[];
  /** Accessible name ("Processes"). */
  label: string;
  /** Unique id of a row (default row.id). */
  rowId?: (row: T) => RowId;
  /** single (default) · multiple (⌘-click, ⇧-click, ⌘A) · none. */
  selectionMode?: SelectionMode;
  selection?: RowId[];
  defaultSelection?: RowId[];
  onSelectionChange?: (ids: RowId[]) => void;
  sort?: TableSort | null;
  defaultSort?: TableSort | null;
  onSortChange?: (sort: TableSort) => void;
  /** Stripes on every other row (default true). */
  alternating?: boolean;
  /** Header stays on top while the rows scroll (put the table in a scrolling box). */
  sticky?: boolean;
  /** An icon at the start of the first column. */
  rowIcon?: (row: T) => IconName;
  /** Double-click or Return on a row (open it). */
  onRowAction?: (row: T) => void;
  /** Shown in one row when there are no rows. */
  emptyText?: ReactNode;
  className?: string;
}

const collator = typeof Intl !== 'undefined' ? new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' }) : null;
function compareValues(a: unknown, b: unknown): number {
  if (a == null && b == null) return 0;
  if (a == null) return -1;
  if (b == null) return 1;
  if (a instanceof Date && b instanceof Date) return a.getTime() - b.getTime();
  if (typeof a === 'number' && typeof b === 'number') return a - b;
  return collator ? collator.compare(String(a), String(b)) : String(a).localeCompare(String(b));
}

/** A table with sortable column headers and selectable rows. Sorting and selection are done for you. */
export function Table<T>({
  columns,
  rows,
  label,
  rowId = (row: T) => (row as unknown as { id: RowId }).id,
  selectionMode = 'single',
  selection,
  defaultSelection = [],
  onSelectionChange,
  sort,
  defaultSort = null,
  onSortChange,
  alternating = true,
  sticky,
  rowIcon,
  onRowAction,
  emptyText,
  className,
}: TableProps<T>) {
  const [currentSort, setSort] = useControllable<TableSort | null>(sort, defaultSort, s => s && onSortChange?.(s));
  const sorted = useMemo(() => {
    if (!currentSort) return rows;
    const col = columns.find(c => c.key === currentSort.key);
    if (!col) return rows;
    const get = col.sortValue ?? ((r: T) => (r as Record<string, unknown>)[col.key] as string | number | undefined);
    const dir = currentSort.direction === 'ascending' ? 1 : -1;
    return [...rows].sort((a, b) => compareValues(get(a), get(b)) * dir);
  }, [rows, columns, currentSort]);
  const ids = useMemo(() => sorted.map(rowId), [sorted, rowId]);
  const sel = useSelection(ids, selectionMode, selection, defaultSelection, onSelectionChange);
  const ref = useRef<HTMLTableElement>(null);

  const clickHeader = (col: TableColumn<T>) => {
    if (col.sortable === false) return;
    const direction: SortDirection = currentSort?.key === col.key && currentSort.direction === 'ascending' ? 'descending' : 'ascending';
    setSort({ key: col.key, direction });
  };

  return (
    <table
      ref={ref}
      className={cx('mac-table', alternating && 'mac-table--alternating', sticky && 'mac-table--sticky', rowIcon && 'mac-table--icons', className)}
      role="grid"
      aria-label={label}
      aria-multiselectable={selectionMode === 'multiple' || undefined}
      tabIndex={selectionMode === 'none' ? undefined : 0}
      onKeyDown={e => {
        if (e.key === 'Enter' && onRowAction) {
          const row = sorted.find(r => sel.set.has(rowId(r)));
          if (row) onRowAction(row);
          return;
        }
        const id = sel.onKeyDown(e);
        if (id != null) scrollRowIntoView(ref.current, id);
      }}
    >
      <colgroup>
        {columns.map(c => (
          <col key={c.key} style={c.width != null ? { width: typeof c.width === 'number' ? `${c.width}px` : c.width } : undefined} />
        ))}
      </colgroup>
      <thead>
        <tr>
          {columns.map(c => (
            <th
              key={c.key}
              scope="col"
              className={c.numeric ? 'mac-table__cell--numeric' : undefined}
              aria-sort={c.sortable === false ? undefined : currentSort?.key === c.key ? currentSort.direction : 'none'}
              onClick={() => clickHeader(c)}
            >
              {c.title}
            </th>
          ))}
        </tr>
      </thead>
      <tbody>
        {sorted.map(row => {
          const id = rowId(row);
          return (
            <tr
              key={id}
              data-value={String(id)}
              aria-selected={selectionMode === 'none' ? undefined : sel.set.has(id)}
              onClick={e => sel.onItemClick(id, e)}
              onContextMenu={() => sel.onItemContextMenu(id)}
              onDoubleClick={onRowAction ? () => onRowAction(row) : undefined}
            >
              {columns.map((c, i) => {
                const content = c.render ? c.render(row) : String((row as Record<string, unknown>)[c.key] ?? '--');
                return (
                  <td key={c.key} className={c.numeric ? 'mac-table__cell--numeric' : undefined}>
                    {i === 0 && rowIcon ? (
                      <div className="mac-table__primary">
                        <span className="mac-table__icon" aria-hidden="true">
                          <Icon name={rowIcon(row)} />
                        </span>
                        <span className="mac-table__text">{content}</span>
                      </div>
                    ) : (
                      content
                    )}
                  </td>
                );
              })}
            </tr>
          );
        })}
        {sorted.length === 0 && emptyText != null && (
          <tr>
            <td colSpan={columns.length} className="mac-label-secondary" style={{ textAlign: 'center' }}>
              {emptyText}
            </td>
          </tr>
        )}
      </tbody>
    </table>
  );
}

