export interface StepperProps {
  value?: number;
  defaultValue?: number;
  onChange?: (value: number) => void;
  min?: number;
  max?: number;
  step?: number;
  /** Accessible name ("Copies"). Inside a <FormRow> the row label is used too. */
  label?: string;
  /** outside (default) = number field + stepper beside it · inside = stepper inside the field · none = stepper only. */
  field?: 'outside' | 'inside' | 'none';
  size?: ControlSize;
  disabled?: boolean;
  id?: string;
}
/** A number with up/down arrows. Holding an arrow repeats. */
export function Stepper({ value, defaultValue, onChange, min = -Infinity, max = Infinity, step = 1, label, field = 'outside', size, disabled, id }: StepperProps) {
  const [current, setCurrent] = useControllable(value, defaultValue ?? (Number.isFinite(min) ? min : 0), onChange);
  const fieldId = useFieldId(id);
  const [draft, setDraft] = useState<string | null>(null);
  const latest = useRef(current);
  latest.current = current;
  const timer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
  const decimals = (String(step).split('.')[1] || '').length;
  const clamp = (n: number) => Math.min(max, Math.max(min, Number(n.toFixed(decimals))));
  const bump = (dir: 1 | -1) => {
    const next = clamp(latest.current + dir * step);
    latest.current = next;
    setCurrent(next);
  };
  const stop = () => clearTimeout(timer.current);
  const start = (dir: 1 | -1) => {
    bump(dir);
    stop();
    const repeat = (delay: number) => {
      timer.current = setTimeout(() => {
        bump(dir);
        repeat(60);
      }, delay);
    };
    repeat(400);
  };
  useEffect(() => stop, []);
  const buttons = (
    <div className="mac-stepper" role="group" aria-label={label}>
      <button
        className="mac-stepper__up"
        type="button"
        aria-label="Increase"
        tabIndex={field === 'none' ? undefined : -1}
        disabled={disabled || current >= max}
        onPointerDown={e => {
          if (e.button === 0) start(1);
        }}
        onPointerUp={stop}
        onPointerLeave={stop}
        onKeyDown={e => {
          if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            bump(1);
          }
        }}
      />
      <button
        className="mac-stepper__down"
        type="button"
        aria-label="Decrease"
        tabIndex={field === 'none' ? undefined : -1}
        disabled={disabled || current <= min}
        onPointerDown={e => {
          if (e.button === 0) start(-1);
        }}
        onPointerUp={stop}
        onPointerLeave={stop}
        onKeyDown={e => {
          if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            bump(-1);
          }
        }}
      />
    </div>
  );
  if (field === 'none') return <span className={sizeClass(size)}>{buttons}</span>;
  return (
    <div className={cx('mac-stepper-field', field === 'outside' && 'mac-stepper-field--outside', sizeClass(size))}>
      <input
        id={fieldId}
        type="number"
        min={Number.isFinite(min) ? min : undefined}
        max={Number.isFinite(max) ? max : undefined}
        step={step}
        disabled={disabled}
        aria-label={label}
        value={draft ?? String(current)}
        onChange={e => {
          setDraft(e.target.value);
          const n = e.target.valueAsNumber;
          if (!Number.isNaN(n) && n >= min && n <= max) setCurrent(n);
        }}
        onBlur={() => setDraft(null)}
        onKeyDown={e => {
          if (e.key === 'ArrowUp' || e.key === 'ArrowDown') {
            e.preventDefault();
            setDraft(null);
            bump(e.key === 'ArrowUp' ? 1 : -1);
          }
        }}
      />
      {buttons}
    </div>
  );
}

