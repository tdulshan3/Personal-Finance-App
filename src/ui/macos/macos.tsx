const sizeClass = (size?: ControlSize) => (size && size !== 'medium' ? `mac-size-${size}` : undefined);
/** style object with CSS custom properties (TypeScript doesn't know them). */
const vars = (style: CSSProperties | undefined, custom: Record<string, string | number | undefined>): CSSProperties => {
  const out: Record<string, unknown> = { ...style };
  for (const [k, v] of Object.entries(custom)) if (v !== undefined) out[k] = v;
  return out as CSSProperties;
};

