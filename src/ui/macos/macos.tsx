export interface ContextMenuProps {
  /** <MenuItem>s shown at the pointer on right-click (Control-click). */
  menu: ReactNode;
  children: ReactNode;
}
/** Right-click menu for its children. Every command in it must also be in the menu bar or toolbar. */
export function ContextMenu({ menu, children }: ContextMenuProps) {
  const popup = usePopup('context');
  return (
    <>
      <div
        style={{ display: 'contents' }}
        onContextMenu={e => {
          const panel = popup.panelRef.current;
          if (!panel) return;
          e.preventDefault();
          popup.point.current = { x: e.clientX, y: e.clientY };
          if (isOpenPopover(panel)) panel.hidePopover();
          panel.showPopover();
        }}
      >
        {children}
      </div>
      <MenuPanel popup={popup} className="mac-context-menu">
        {menu}
      </MenuPanel>
    </>
  );
}

