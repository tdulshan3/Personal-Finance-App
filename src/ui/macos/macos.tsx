export interface TitlebarProps extends Omit<HTMLAttributes<HTMLElement>, 'title'> {
  /** The window title: the document or current view ("Inbox", "Budget 2027"), not the app name. */
  title?: ReactNode;
  /** Grey line under the title: a count, "Edited", or a live status ("Connecting…", "Updated 9:41"). */
  subtitle?: ReactNode;
  /** Small icon before the title (document windows). */
  icon?: IconName;
  /** unified (default, 52 px) · compact (40 px) · expanded (title row + toolbar row) · none (31 px bar, title only). */
  toolbarStyle?: 'unified' | 'compact' | 'expanded' | 'none';
  /** Toolbar items BEFORE the title (a <SidebarToggle />, a back/forward group). */
  leading?: ReactNode;
  /** Draw traffic lights (mockups only). */
  windowControls?: boolean;
  /** Push the toolbar items (children) to the right edge (default true). */
  spacer?: boolean;
}
/** The title bar + toolbar. Children are toolbar items: <ToolbarButton>, <ToolbarGroup>, <SearchField>, <SegmentedControl>, <PopUpButton>… */
export function Titlebar({
  title,
  subtitle,
  icon,
  toolbarStyle = 'unified',
  leading,
  windowControls,
  spacer = true,
  className,
  children,
  ...rest
}: TitlebarProps) {
  const lights = windowControls ? <WindowControls /> : null;
  const heading =
    title != null || subtitle != null ? (
      <div className="mac-titlebar__heading">
        {icon && <Icon name={icon} className="mac-titlebar__icon" />}
        <div className="mac-titlebar__text">
          {title != null && <h1 className="mac-titlebar__title">{title}</h1>}
          {subtitle != null && <p className="mac-titlebar__subtitle">{subtitle}</p>}
        </div>
      </div>
    ) : null;

  if (toolbarStyle === 'none') {
    return (
      <header className={cx('mac-titlebar', className)} {...rest}>
        {lights}
        {title != null && <h1 className="mac-titlebar__title">{title}</h1>}
      </header>
    );
  }
  if (toolbarStyle === 'expanded') {
    return (
      <header className={cx('mac-titlebar', 'mac-titlebar--expanded', 'mac-size-xl', className)} {...rest}>
        {lights}
        {title != null && <h1 className="mac-titlebar__title">{title}</h1>}
        <div className="mac-toolbar">
          {leading}
          {children}
        </div>
      </header>
    );
  }
  return (
    <header
      className={cx('mac-titlebar', `mac-titlebar--${toolbarStyle}`, toolbarStyle === 'unified' && 'mac-size-xl', className)}
      {...rest}
    >
      {lights}
      <div className="mac-toolbar">
        {leading}
        {heading}
        {spacer && <span className="mac-toolbar__spacer" />}
        {children}
      </div>
    </header>
  );
}

