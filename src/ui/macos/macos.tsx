export type RowId = string | number;
export type SelectionMode = 'none' | 'single' | 'multiple';

function useSelection(ids: RowId[], mode: SelectionMode, selection: RowId[] | undefined, defaultSelection: RowId[], onChange?: (ids: RowId[]) => void) {
  const [selected, setSelected] = useControllable(selection, defaultSelection, onChange);
  const anchor = useRef<RowId | null>(null);
  const lead = useRef<RowId | null>(null);
  const set = useMemo(() => new Set(selected), [selected]);

  const range = (a: RowId, b: RowId) => {
    const i = ids.indexOf(a);
    const j = ids.indexOf(b);
    if (i < 0 || j < 0) return [b];
    return ids.slice(Math.min(i, j), Math.max(i, j) + 1);
  };

  const onItemClick = (id: RowId, e: ReactMouseEvent) => {
    if (mode === 'none') return;
    const toggleKey = isApple() ? e.metaKey : e.ctrlKey;
    if (mode === 'multiple' && toggleKey) {
      setSelected(set.has(id) ? selected.filter(x => x !== id) : [...selected, id]);
      anchor.current = id;
    } else if (mode === 'multiple' && e.shiftKey && anchor.current != null) {
      setSelected(range(anchor.current, id));
    } else {
      setSelected([id]);
      anchor.current = id;
    }
    lead.current = id;
  };

  /** Returns the id to scroll into view, if the key moved the selection. */
  const onKeyDown = (e: ReactKeyboardEvent): RowId | null => {
    if (mode === 'none' || ids.length === 0) return null;
    const cmd = isApple() ? e.metaKey : e.ctrlKey;
    if (cmd && e.key.toLowerCase() === 'a' && mode === 'multiple') {
      e.preventDefault();
      setSelected([...ids]);
      return null;
    }
    const cur = lead.current != null && ids.includes(lead.current) ? ids.indexOf(lead.current) : ids.findIndex(id => set.has(id));
    let next = -1;
    if (e.key === 'ArrowDown') next = cur < 0 ? 0 : Math.min(cur + 1, ids.length - 1);
    else if (e.key === 'ArrowUp') next = cur < 0 ? ids.length - 1 : Math.max(cur - 1, 0);
    else if (e.key === 'Home') next = 0;
    else if (e.key === 'End') next = ids.length - 1;
    else return null;
    e.preventDefault();
    const id = ids[next];
    if (mode === 'multiple' && e.shiftKey && anchor.current != null) setSelected(range(anchor.current, id));
    else {
      setSelected([id]);
      anchor.current = id;
    }
    lead.current = id;
    return id;
  };

  /** Right-click on a row that isn't selected: select it first (like the Finder), so a context menu acts on it. */
  const onItemContextMenu = (id: RowId) => {
    if (mode === 'none' || set.has(id)) return;
    setSelected([id]);
    anchor.current = id;
    lead.current = id;
  };

  return { set, onItemClick, onItemContextMenu, onKeyDown };
}

function scrollRowIntoView(root: HTMLElement | null, id: RowId) {
  const el = root?.querySelector(`[data-value="${typeof CSS !== 'undefined' && CSS.escape ? CSS.escape(String(id)) : String(id)}"]`);
  el?.scrollIntoView({ block: 'nearest' });
}

