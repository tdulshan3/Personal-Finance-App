/** Value that is controlled (value + onChange) or uncontrolled (defaultValue). */
function useControllable<T>(value: T | undefined, defaultValue: T, onChange?: (v: T) => void): [T, (v: T) => void] {
  const [inner, setInner] = useState<T>(defaultValue);
  const controlled = value !== undefined;
  const current = controlled ? (value as T) : inner;
  const set = useCallback(
    (v: T) => {
      if (!controlled) setInner(v);
      onChange?.(v);
    },
    [controlled, onChange],
  );
  return [current, set];
}

/** FormRow gives its control an id, so the row label points at it without you writing ids. */
const FieldIdContext = createContext<string | undefined>(undefined);
function useFieldId(id?: string): string {
  const fromRow = useContext(FieldIdContext);
  const own = useId();
  return id ?? fromRow ?? own;
}

