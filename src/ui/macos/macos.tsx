function useBrowserWindowFocused(enabled: boolean): boolean {
  const [focused, setFocused] = useState(true);
  useEffect(() => {
    if (!enabled) return;
    const onFocus = () => setFocused(true);
    const onBlur = () => setFocused(false);
    window.addEventListener('focus', onFocus);
    window.addEventListener('blur', onBlur);
    return () => {
      window.removeEventListener('focus', onFocus);
      window.removeEventListener('blur', onBlur);
    };
  }, [enabled]);
  return focused;
}

export interface WindowProps extends HTMLAttributes<HTMLDivElement> {
  /** page (default) = the whole browser tab / Electron / Tauri window. window = a drawn Mac window (mockups; give it a size). utility = small floating panel. */
  variant?: 'page' | 'window' | 'utility';
  /** Draw the window as not focused (grey accent, no selection colour). */
  inactive?: boolean;
  /** Turn inactive while the browser window is in the background (default true). */
  trackFocus?: boolean;
  /** The <Sidebar> is hidden (View › Hide Sidebar). Leave it out and the window keeps this state itself:
   *  a <SidebarToggle /> in the title bar then works with no wiring. */
  sidebarHidden?: boolean;
  /** Start with the sidebar hidden (when the window keeps the state itself). */
  defaultSidebarHidden?: boolean;
  /** Called with the new value when a <SidebarToggle> is clicked. */
  onSidebarHiddenChange?: (hidden: boolean) => void;
}

const SidebarStateContext = createContext<{ hidden: boolean; setHidden: (hidden: boolean) => void } | null>(null);

/** The root of the app: <Window> directly inside <body> / #root. It fills the viewport; only <Content> scrolls. */
export function Window({
  variant = 'page',
  inactive,
  trackFocus = true,
  sidebarHidden,
  defaultSidebarHidden = false,
  onSidebarHiddenChange,
  className,
  children,
  ...rest
}: WindowProps) {
  const focused = useBrowserWindowFocused(trackFocus);
  const [ownHidden, setOwnHidden] = useState(defaultSidebarHidden);
  const hidden = sidebarHidden ?? ownHidden;
  const sidebar = useMemo(
    () => ({
      hidden,
      setHidden: (next: boolean) => {
        if (sidebarHidden === undefined) setOwnHidden(next);
        onSidebarHiddenChange?.(next);
      },
    }),
    [hidden, sidebarHidden, onSidebarHiddenChange],
  );
  return (
    <SidebarStateContext.Provider value={sidebar}>
      <div
        className={cx(
          'mac-window',
          variant === 'page' && 'mac-window--page',
          variant === 'utility' && 'mac-window--utility',
          hidden && 'mac-window--sidebar-hidden',
          (inactive || (trackFocus && !focused)) && 'mac-inactive',
          className,
        )}
        {...rest}
      >
        {children}
      </div>
    </SidebarStateContext.Provider>
  );
}

export interface SidebarToggleProps extends Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'children' | 'onChange'> {
  /** Id of the <Sidebar> (for aria-controls). */
  sidebarId?: string;
}
/**
 * Show/Hide Sidebar: the FIRST item of the main pane's title bar (`<Titlebar leading={<SidebarToggle />}>`).
 * It hides and shows the <Sidebar> of its <Window> (the main pane then fills the window) and keeps its label
 * ("Hide Sidebar" / "Show Sidebar") and aria-expanded in step. Same markup as the web version (data-mac-toggle-sidebar).
 */
export function SidebarToggle({ sidebarId, className, onClick, ...rest }: SidebarToggleProps) {
  const state = useContext(SidebarStateContext);
  const hidden = state?.hidden ?? false;
  const label = hidden ? 'Show Sidebar' : 'Hide Sidebar';
  return (
    <button
      className={cx('mac-toolbar__item', className)}
      type="button"
      data-mac-toggle-sidebar=""
      aria-label={label}
      title={label}
      aria-expanded={!hidden}
      aria-controls={sidebarId}
      onClick={e => {
        onClick?.(e);
        if (e.defaultPrevented) return;
        e.preventDefault(); // handled here: macos.js (if it is on the page anyway) leaves the click alone
        state?.setHidden(!hidden);
      }}
      {...rest}
    >
      <Icon name="sidebar-left" />
    </button>
  );
}

