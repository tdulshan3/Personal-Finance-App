function useModal(ref: RefObject<HTMLDialogElement | null>, open: boolean, onCancel: () => void) {
  const cancel = useRef(onCancel);
  cancel.current = onCancel;
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal();
    if (!open && d.open) d.close();
  }, [ref, open]);
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    const onCancelEvent = (e: Event) => {
      e.preventDefault(); // stay open until the parent sets open={false}
      cancel.current();
    };
    d.addEventListener('cancel', onCancelEvent);
    return () => d.removeEventListener('cancel', onCancelEvent);
  }, [ref]);
}

export interface DialogButton {
  label: string;
  /** default = the prominent button (Return) · destructive · cancel (Escape) · normal · leading (sheets: pushed to the left). */
  role?: 'default' | 'destructive' | 'cancel' | 'normal' | 'leading';
  onClick?: () => void;
  disabled?: boolean;
}

export interface AlertProps {
  open: boolean;
  /** Called with the label of the button that closed it (Escape = the cancel button's label). Set open to false here. */
  onClose: (buttonLabel?: string) => void;
  /** Bold question or statement ("Delete “Budget 2027”?"). */
  title: ReactNode;
  /** Short explanation (optional). */
  message?: ReactNode;
  /** 64 px app icon URL (optional). */
  icon?: string;
  /** Default: one "OK" button. Order doesn't matter: default → destructive → cancel is applied for you. */
  buttons?: DialogButton[];
  /** "Don't ask again" checkbox. */
  suppression?: { label: string; checked: boolean; onChange: (checked: boolean) => void };
  /** auto (default) = two short buttons side by side, otherwise stacked. */
  layout?: 'auto' | 'stacked' | 'side-by-side';
}
/** A modal alert (panel material, centred, dims the window). Use it rarely: only for important, irreversible things. */
export function Alert({ open, onClose, title, message, icon, buttons = [{ label: 'OK', role: 'default' }], suppression, layout = 'auto' }: AlertProps) {
  const ref = useRef<HTMLDialogElement>(null);
  const ids = useId();
  const order = { default: 0, destructive: 1, normal: 2, leading: 2, cancel: 3 } as const;
  const sorted = [...buttons].sort((a, b) => order[a.role ?? 'normal'] - order[b.role ?? 'normal']);
  const cancelBtn = sorted.find(b => b.role === 'cancel');
  const sideBySide = layout === 'side-by-side' || (layout === 'auto' && sorted.length === 2 && sorted.every(b => b.label.length <= 12));
  useModal(ref, open, () => {
    cancelBtn?.onClick?.();
    onClose(cancelBtn?.label);
  });
  useEffect(() => {
    // Return triggers the default button: give it the focus (showModal would focus the first control).
    if (open) ref.current?.querySelector<HTMLButtonElement>('.mac-alert__buttons .mac-button--prominent')?.focus();
  }, [open]);
  return (
    <dialog
      ref={ref}
      className={cx('mac-alert', sideBySide && 'mac-alert--side-by-side')}
      aria-labelledby={`${ids}-t`}
      aria-describedby={message != null ? `${ids}-m` : undefined}
    >
      {icon && <img className="mac-alert__icon" src={icon} alt="" />}
      <h2 className="mac-alert__title" id={`${ids}-t`}>
        {title}
      </h2>
      {message != null && (
        <p className="mac-alert__message" id={`${ids}-m`}>
          {message}
        </p>
      )}
      {suppression && (
        <label className="mac-alert__suppression">
          <input type="checkbox" className="mac-checkbox" checked={suppression.checked} onChange={e => suppression.onChange(e.target.checked)} />{' '}
          {suppression.label}
        </label>
      )}
      <form method="dialog" className="mac-alert__buttons" onSubmit={e => e.preventDefault()}>
        {sorted.map(b => (
          <button
            key={b.label}
            type="button"
            disabled={b.disabled}
            className={cx('mac-button', b.role === 'default' && 'mac-button--prominent', b.role === 'destructive' && 'mac-button--destructive')}
            onClick={() => {
              b.onClick?.();
              onClose(b.label);
            }}
          >
            {b.label}
          </button>
        ))}
      </form>
    </dialog>
  );
}

export interface SheetProps {
  open: boolean;
  /** Called with the label of the button that closed it (Escape = the cancel button's label). Set open to false here. */
  onClose: (buttonLabel?: string) => void;
  title?: ReactNode;
  /** Buttons at the bottom right. The default one runs on Return. Order is applied for you. */
  buttons?: DialogButton[];
  /** Gap from the top of the viewport in px (default 8; below a 52 px toolbar use 60). */
  top?: number;
  children?: ReactNode;
}
/** A modal panel that slides down from the top of the window (Save / Rename / New Project). */
export function Sheet({ open, onClose, title, buttons = [], top, children }: SheetProps) {
  const ref = useRef<HTMLDialogElement>(null);
  const ids = useId();
  const order = { leading: 0, normal: 1, destructive: 1, cancel: 2, default: 3 } as const;
  const sorted = [...buttons].sort((a, b) => order[a.role ?? 'normal'] - order[b.role ?? 'normal']);
  const cancelBtn = sorted.find(b => b.role === 'cancel');
  const defaultBtn = sorted.find(b => b.role === 'default');
  useModal(ref, open, () => {
    cancelBtn?.onClick?.();
    onClose(cancelBtn?.label);
  });
  return (
    <dialog
      ref={ref}
      className="mac-sheet"
      aria-labelledby={title != null ? `${ids}-t` : undefined}
      style={vars(undefined, { '--mac-sheet-top': top != null ? `${top}px` : undefined })}
    >
      <form
        method="dialog"
        onSubmit={e => {
          e.preventDefault();
          if (defaultBtn && !defaultBtn.disabled) {
            defaultBtn.onClick?.();
            onClose(defaultBtn.label);
          }
        }}
      >
        {title != null && (
          <h2 className="mac-sheet__title" id={`${ids}-t`}>
            {title}
          </h2>
        )}
        <div className="mac-sheet__content">{children}</div>
        {sorted.length > 0 && (
          <div className="mac-sheet__buttons">
            {sorted.map(b => (
              <button
                key={b.label}
                type={b.role === 'default' ? 'submit' : 'button'}
                disabled={b.disabled}
                className={cx(
                  'mac-button',
                  b.role === 'default' && 'mac-button--prominent',
                  b.role === 'destructive' && 'mac-button--destructive',
                  b.role === 'leading' && 'mac-sheet__leading',
                )}
                onClick={
                  b.role === 'default'
                    ? undefined
                    : () => {
                        b.onClick?.();
                        onClose(b.label);
                      }
                }
              >
                {b.label}
              </button>
            ))}
          </div>
        )}
      </form>
    </dialog>
  );
}

